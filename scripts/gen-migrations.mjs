// Inlines the SQL migrations (drizzle/*.sql) into db/demo-migrations.ts so demo mode needs no files on disk
// (serverless hosts such as Vercel only ship what the code imports). Runs before dev and build.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));
const migrations = journal.entries.map((e) => {
  const query = readFileSync(`drizzle/${e.tag}.sql`, "utf8");
  return { sql: query.split("--> statement-breakpoint"), bps: e.breakpoints, folderMillis: e.when, hash: createHash("sha256").update(query).digest("hex") };
});
const out = `// GENERATED by scripts/gen-migrations.mjs from drizzle/*.sql: do not edit by hand.\nexport const DEMO_MIGRATIONS = ${JSON.stringify(migrations, null, 1)};\n`;
writeFileSync("db/demo-migrations.ts", out);
console.log(`Inlined ${migrations.length} migrations into db/demo-migrations.ts`);
